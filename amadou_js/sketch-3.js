function setup() {
  // creates a canvas 600 pixels wide and 400 height
  createCanvas(700, 700);
}
function draw() {
  //sky blue background
  background(135, 206, 255);
  //sun in top-right corner
  // fill with yellow
  fill("yellow");
  //orange outline use stroke
  stroke("orange");
  //large outline use strokeWeight
  strokeWeight(5);
  //circle
  circle(540, 55, 67);
fill(rgba, 0, 0, 0)
  //grass field
  //fill green
  fill("lime");
  //green outline use stroke
  stroke("yellow");
  rect(0, 170, 600, 228);

  //add emoji
  // add text
  textSize(130);
  text("🫠", 3, 175);
  text("👆🏾", mouseX, mouseY);
}
